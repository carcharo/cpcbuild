test('importer: change an option, save, the .bas equals the committed asset (builtin engine)', async () => {
  const rel = 'examples/assets/balls.bas';
  const r = recipeFor(rel);
  const wrong = { ...r };
  delete wrong.masked;
  const uri = writeRecipe('assets/balls.cpcimp', wrong);
  const { a, doc } = await openImporter(uri);
  assert.strictEqual(doc.state.masked, undefined);
  a.importer.commit(doc, { op: 'set', patch: { masked: true } });
  assert.strictEqual(doc.state.masked, true);
  assert.strictEqual(doc.undoDepth, 1);
  await vscode.commands.executeCommand('workbench.action.files.save');
  await waitFor('output generated on save', () => fs.existsSync(path.join(ws, rel)) && read(rel) === committed(rel));
  assert.strictEqual(JSON.parse(read('assets/balls.cpcimp')).masked, true);
  // undo/redo go through the document
  assert.ok(a.importer.undoLast(doc));
  assert.strictEqual(doc.state.masked, undefined);
  assert.ok(a.importer.redoLast(doc));
  await closeClean();
  rm('assets/balls.cpcimp');
});

test('importer: Regenerate Assets runs every recipe; engine=python gives the same bytes', async () => {
  const targets = ['examples/assets/balls.bas', 'examples/assets/bgtiles.bas', 'tests/conformance/assets/spr1.bas', 'tests/conformance/assets/plus_ballpk.bas'];
  targets.forEach((rel, n) => writeRecipe(`assets/r${n}.cpcimp`, recipeFor(rel)));
  const generated = (): void => targets.forEach((rel) => assert.strictEqual(read(rel), committed(rel), rel));
  const run = async (): Promise<void> => {
    const res = (await vscode.commands.executeCommand('cpcbuild.regenerateAssets', { root: ws })) as { recipe: string; ok: boolean; error?: string }[];
    const mine = res.filter((x) => /assets\/r\d\.cpcimp$/.test(x.recipe));
    assert.deepStrictEqual(mine.map((x) => x.error ?? 'ok'), mine.map(() => 'ok'));
    assert.strictEqual(mine.length, targets.length);
  };
  rm(...targets);
  await run();
  generated();
  rm(...targets);
  await setting('assets.engine', 'python');
  try {
    await run();
    generated();
  } finally {
    await setting('assets.engine', undefined);
  }
  // header modes
  await setting('assets.header', 'none');
  try {
    await run();
    assert.ok(read(targets[0]).startsWith('DIM balls('), 'no header');
  } finally {
    await setting('assets.header', undefined);
  }
  rm('assets/r0.cpcimp', 'assets/r1.cpcimp', 'assets/r2.cpcimp', 'assets/r3.cpcimp', ...targets);
});

test('importer: a failing recipe reports the tool\'s text and Regenerate keeps going', async () => {
  const bad = recipeFor('tests/conformance/assets/spr1.bas');
  writeRecipe('assets/bad.cpcimp', { ...bad, palette: undefined, mode: 2, output: 'assets/bad.bas' });
  writeRecipe('assets/good.cpcimp', { ...recipeFor('tests/conformance/assets/msk1.bas'), output: 'assets/good.bas' });
  const res = (await vscode.commands.executeCommand('cpcbuild.regenerateAssets', { root: ws })) as { recipe: string; ok: boolean; error?: string }[];
  const b = res.find((x) => x.recipe === 'assets/bad.cpcimp');
  const g = res.find((x) => x.recipe === 'assets/good.cpcimp');
  assert.ok(b && !b.ok && /^img2cpc: the image needs \d+ colours/.test(b.error ?? ''), b?.error);
  assert.ok(g?.ok, g?.error);
  assert.ok(fs.existsSync(path.join(ws, 'assets/good.bas')));
  rm('assets/bad.cpcimp', 'assets/bad.bas', 'assets/good.cpcimp', 'assets/good.bas');
});

test('importer: the build regenerates a stale asset before compiling', async () => {
  const a = await api();
  const r = recipeFor('tests/conformance/assets/spr1.bas');
  writeRecipe('assets/stale.cpcimp', { ...r, output: 'assets/stale.bas' });
  rm('assets/stale.bas');
  const res = await a.build(fs.realpathSync(ws), 'cpc6128');
  assert.ok(res.ok, res.message);
  assert.ok(fs.existsSync(path.join(ws, 'assets/stale.bas')), 'the stale output was regenerated by the build');
  // a failing recipe fails the build with its message
  writeRecipe('assets/stale.cpcimp', { ...r, mode: 2, palette: undefined, output: 'assets/stale.bas' });
  rm('assets/stale.bas');
  const bad = await a.build(fs.realpathSync(ws), 'cpc6128');
  assert.ok(!bad.ok && /asset assets\/stale\.cpcimp: img2cpc: the image needs/.test(bad.message ?? ''), bad.message);
  // and the setting turns it off
  await setting('assets.regenerateBeforeBuild', false);
  try {
    const off = await a.build(fs.realpathSync(ws), 'cpc6128');
    assert.ok(off.ok, off.message);
  } finally {
    await setting('assets.regenerateBeforeBuild', undefined);
  }
  rm('assets/stale.cpcimp', 'assets/stale.bas');
});

test('importer: requests - preview, command import, copy command, grid blocks the copy', async () => {
  const r = recipeFor('tests/conformance/assets/spr1.bas');
  const uri = writeRecipe('assets/req.cpcimp', { ...r, output: 'assets/req.bas' });
  const { a, doc } = await openImporter(uri);
  const p = a.importer as unknown as { request(d: unknown, name: string, args: unknown): Promise<any> };
  const pv = await p.request(doc, 'preview', { version: doc.version });
  assert.ok(pv.ok, pv.error);
  assert.strictEqual(pv.preview.rows.length, 4);
  assert.match(pv.preview.summary, /frame\(s\)/);
  // the command box text
  const view = (a.importer as unknown as { currentView(d: unknown): any }).currentView(doc);
  assert.strictEqual(view.command, 'python3 tools/img2cpc.py --mode 1 --name a_spr1 --palette 0,26,6,18 tests/conformance/assets/spr1.png -o assets/req.bas');
  // a pasted build_assets.sh line replaces the recipe (keeping the output when the line has none)
  const imp = await p.request(doc, 'importCommand', { baseVersion: doc.version, line: '$I --mode 1 --name a_msk1 --masked --palette 0,26,6,18 $C/msk1.png' });
  assert.ok(imp.ok, imp.error);
  assert.deepStrictEqual(imp.unrecognised, ['$C/msk1.png']);
  assert.strictEqual(doc.state.output, 'assets/req.bas');
  const bad = await p.request(doc, 'importCommand', { baseVersion: doc.version, line: 'img2cpc.py --mode 9 x.png' });
  assert.ok(!bad.ok);
  assert.strictEqual(bad.error, "argument --mode: invalid choice: '9' (choose from 0, 1, 2)");
  // grid on: no command
  a.importer.commit(doc, { op: 'set', patch: { source: 'tests/conformance/assets/spr1.png', grid: { cellW: 4, cellH: 4, marginX: 0, marginY: 0, spacingX: 0, spacingY: 0, exclude: [] } } });
  const v2 = (a.importer as unknown as { currentView(d: unknown): any }).currentView(doc);
  assert.strictEqual(v2.command, undefined);
  assert.match(v2.commandReason, /grid extraction/);
  const cp = await p.request(doc, 'copyCommand', {});
  assert.strictEqual(cp.copied, false);
  a.importer.commit(doc, { op: 'cells', cells: [0], include: false });
  assert.deepStrictEqual(doc.state.grid?.exclude, [0]);
  // a stale edit is refused
  await assert.rejects(p.request(doc, 'edit', { baseVersion: doc.version + 3, op: { op: 'set', patch: { name: 'x' } } }), /changed in another view/);
  await closeClean();
  rm('assets/req.cpcimp');
});

test('importer: a 16-bit PNG is refused with the way out; useEngine switches to python', async () => {
  const img = path.join(ws, 'art16.png');
  const py = require('child_process').spawnSync(python().cmd, [...python().pre, '-c', `from PIL import Image\nImage.new('I;16',(8,4),1000).save(${JSON.stringify(img)})`]);
  assert.strictEqual(py.status, 0);
  const uri = writeRecipe('assets/wide.cpcimp', { format: 'cpcimp', version: 1, source: 'art16.png', target: 'cpc', mode: 1, output: 'assets/wide.bas' });
  const { a, doc } = await openImporter(uri);
  const p = a.importer as unknown as { request(d: unknown, name: string, args: unknown): Promise<any>; confirmOverride?: boolean };
  const pv = await p.request(doc, 'preview', { version: doc.version });
  assert.ok(!pv.ok && /16-bit PNG.*python/.test(pv.error), pv.error);
  const src = await p.request(doc, 'sourceImage', {});
  assert.ok(!src.ok && /16-bit PNG/.test(src.error));
  p.confirmOverride = true;
  const u = await p.request(doc, 'useEngine', { engine: 'python' });
  assert.ok(u.changed);
  assert.strictEqual(vscode.workspace.getConfiguration('cpcbuild').get('assets.engine'), 'python');
  await setting('assets.engine', undefined);
  p.confirmOverride = undefined;
  await closeClean();
  rm('assets/wide.cpcimp', 'art16.png');
});
