export type HeaderMode = 'img2cpc' | 'studio' | 'none';

export interface RunOptions {
  header?: HeaderMode;
  /** Path of the .cpcimp (project-relative), for the "studio" header. */
  recipePath?: string;
  /** Called with the decoded source: lets the host cache images. */
  decode?: (path: string, bytes: Uint8Array) => RgbaImage;
}

export interface RunOutput {
  argv: string[];
  result: Result;
  /** Files to write (project-relative paths), with the header already restyled. */
  files: { path: string; data: string | Uint8Array }[];
}

/** A usage error: img2cpc.py's argparse prints `img2cpc.py: error: <message>` for these. */
export class UsageError extends Error {
  constructor(message: string) {
    super(`img2cpc.py: error: ${message}`);
    this.name = 'UsageError';
  }
}

/** The tool's error text as the command line prints it (`img2cpc: ` for conversion errors, `img2cpc.py: error: ` for usage errors). */
export function toolMessage(e: unknown): string {
  if (e instanceof UsageError) return e.message;
  const m = e instanceof Error ? e.message : String(e);
  return `img2cpc: ${m}`;
}

/** Replaces the 5-line header of generated text (4 comment lines and a blank line). */
export function restyleHeader(text: string, mode: HeaderMode, recipePath: string | undefined): string {
  if (mode === 'img2cpc') return text;
  const lines = text.split('\n');
  const cmt = lines[0].startsWith(';') ? ';' : "'";
  if (!lines[0].startsWith(`${cmt} Generated by img2cpc.py`)) return text;
  if (mode === 'none') return lines.slice(5).join('\n');
  lines[0] = `${cmt} Generated by CPCBuild Studio from ${recipePath ?? 'a .cpcimp recipe'}`;
  lines[3] = `${cmt} Do not edit; regenerate with "CPCBuild: Regenerate Assets".`;
  return lines.join('\n');
}

function readSourceImage(io: CliIo, path: string, decode?: RunOptions['decode']): RgbaImage {
  let bytes: Uint8Array;
  try {
    bytes = io.readFile(path);
  } catch (e) {
    if (e instanceof Img2cpcError || (e as NodeJS.ErrnoException).code === 'ENOENT') throw new UsageError(`${path}: not found`);
    throw e;
  }
  try {
    return decode ? decode(path, bytes) : decodeImage(bytes);
  } catch (e) {
    if (e instanceof ImageReadError) throw new Img2cpcError(`${path}: ${e.message}`);
    throw e;
  }
}

/** The recipe's command line parsed like the tool does; its usage errors are UsageErrors. The palette file is not read yet. */
export function optionsOf(r: Recipe): { args: CliArgs; argv: string[] } {
  const argv = recipeToArgv(r);
  try {
    return { args: parseArgs(argv), argv };
  } catch (e) {
    if (e instanceof Img2cpcError) throw new UsageError(e.message);
    throw e;
  }
}

/** Reads the palette file into the options (after the image, as the tool does). */
function readPaletteFile(a: CliArgs, io: CliIo): void {
  if (a.paletteFile !== undefined) a.options.palette = io.readText(a.paletteFile);
}

/** Runs a recipe with the built-in engine: the same steps as `runCli`, plus grid extraction and header styling. */
export function runRecipe(r: Recipe, io: CliIo, opts: RunOptions = {}): RunOutput {
  const { args: a, argv } = optionsOf(r);
  const o = a.options;
  let img = readSourceImage(io, a.image, opts.decode);
  readPaletteFile(a, io);
  if (r.grid) img = composeSheet(img, r.grid);
  const result = convert(img, o, { argv, source: normPath(a.image) });
  const mode = opts.header ?? 'img2cpc';
  const files: RunOutput['files'] = [];
  if (a.writePalette && result.paletteFile) files.push({ path: a.writePalette, data: result.paletteFile });
  if (o.plusFormat === 'bin') {
    files.push({ path: a.output!, data: result.bin! });
    if (result.palBin) files.push({ path: a.output!.replace(/\.[^./]*$/, '') + '.pal', data: result.palBin });
  } else {
    files.push({ path: a.output!, data: restyleHeader(result.text, mode, opts.recipePath) });
  }
  return { argv, result, files };
}

// ------------------------------------------------------------------ preview

export interface PenRow {
  /** Pen number (or palette index for Plus). */
  pen: number;
  /** CPC: firmware colour; Plus: the 12-bit colour as three hex digits. */
  label: string;
  rgb: [number, number, number];
  /** How many distinct source colours land on this pen. */
  colours: number;
  pixels: number;
}

export interface Preview {
  width: number;
  height: number;
  /** Pen index per pixel; 255 = transparent. */
  indices: number[];
  rows: PenRow[];
  transparent: number;
  /** The converter's description line ("3 frame(s) of 4 bytes x 16 lines, ..."). */
  summary: string;
  /** The generated text (empty for Plus bin). */
  text: string;
}

export const TRANSPARENT_INDEX = 255;

/** The quantised picture the converter would produce, for display. The host codec only; the webview never quantises. */
export function previewOf(r: Recipe, io: CliIo, opts: RunOptions = {}): Preview {
  const out = runRecipe(r, io, { ...opts, header: 'img2cpc' });
  const { args: a } = optionsOf(r);
  const o = a.options;
  let img = readSourceImage(io, a.image, opts.decode);
  readPaletteFile(a, io);
  if (r.grid) img = composeSheet(img, r.grid);
  const pix = toPix(img, o.transparent);
  const w = img.width, h = img.height;
  const summary = out.result.text.split('\n')[2]?.replace(/^[;'] /, '') ?? '';
  const indices: number[] = new Array(w * h).fill(TRANSPARENT_INDEX);
  const rows: PenRow[] = [];
  let transparent = 0;
  const colourSets: Set<string>[] = [];
  const count = (pen: number, p: RGB | null, i: number): void => {
    if (!p) {
      transparent++;
      return;
    }
    indices[i] = pen;
    rows[pen].pixels++;
    colourSets[pen].add(p.join(','));
  };
  if (o.plusSprite || o.plusPalette) {
    let fixed: RGB[] | undefined;
    if (o.palette !== undefined) fixed = parseRgb12List(o.palette);
    const pal: RGB[] = fixed ? [...fixed] : [];
    if (!fixed) {
      const seen = new Set<string>();
      for (const row of pix) for (const p of row) if (p) {
        const c = rgb12(p);
        if (!seen.has(c.join(','))) {
          seen.add(c.join(','));
          pal.push(c);
        }
      }
    }
    pal.forEach((c, n) => {
      rows.push({ pen: n, label: c.map((v) => v.toString(16).toUpperCase()).join(''), rgb: [c[0] * 17, c[1] * 17, c[2] * 17], colours: 0, pixels: 0 });
      colourSets.push(new Set());
    });
    if (pal.length) pix.forEach((row, y) => row.forEach((p, x) => count(p ? nearest(rgb12(p), pal) : -1, p, y * w + x)));
  } else if (o.spectrum) {
    throw new Img2cpcError('there is no CPC preview of Spectrum output');
  } else {
    const fixed = o.palette !== undefined ? parsePalList(o.palette) : undefined;
    const pal = buildPalette(pix, o.mode!, fixed, o.pen0);
    pal.forEach((fw, n) => {
      rows.push({ pen: n, label: String(fw), rgb: [...FW_TABLE[fw]] as [number, number, number], colours: 0, pixels: 0 });
      colourSets.push(new Set());
    });
    const grid = penGrid(pix, pal);
    grid.forEach((row, y) => row.forEach((pen, x) => count(pen ?? -1, pix[y][x], y * w + x)));
  }
  rows.forEach((row, n) => (row.colours = colourSets[n].size));
  return { width: w, height: h, indices, rows, transparent, summary, text: out.result.text };
}

/** Pens the mode offers (UI hint). */
export function penCount(r: Recipe): number | undefined {
  return r.target === 'cpc' && r.mode !== undefined ? MAXPENS[r.mode] : undefined;
}

