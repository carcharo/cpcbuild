/**
 * cpcimp.ts -- the importer recipe (.cpcimp): model, JSON round trip, the mapping to and from an
 * `img2cpc.py` command line, grid extraction, running the converter and the live preview data.
 *
 * Spec 4.4. A recipe is one JSON object; every field has exactly one flag of tools/img2cpc.py:
 *
 *   { "format": "cpcimp", "version": 1,
 *     "source": "art/hero.png", "output": "assets/hero.bas",
 *     "target": "cpc", "mode": 1, "name": "hero", "kind": "sprite",
 *     "frame": "16x16", "masked": true, "transparent": "FF00FF",
 *     "palette": {"list": [0, 26, 6, 18]}, "emitPalette": true }
 *
 * Paths are relative to the project root (the folder of cpcbuild.json) with forward slashes, which
 * is also the directory img2cpc.py is run from, so its header (`' Generated by img2cpc.py <argv>`,
 * `' Source: <path>`) is the same text the build scripts produce. The argv is built in one fixed
 * order (see `recipeToArgv`), so a recipe made from tools/build_assets.sh lines regenerates the
 * committed files byte for byte.
 *
 * Pre-processing that has no flag (grid extraction) lives in the recipe's `grid` and produces a
 * composed sheet that is fed to the unchanged converter; the "copy command" is then unavailable.
 *
 * Pure TypeScript; file access is injected (`CliIo`). No vscode or node imports.
 */
