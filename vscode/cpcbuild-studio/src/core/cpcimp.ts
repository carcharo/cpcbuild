export type ImportTarget = 'cpc' | 'plus-sprite' | 'plus-palette' | 'spectrum';
export type PlusFormat = 'bas' | 'asm' | 'bin';

export interface PalRef {
  /** CPC modes: firmware colours; Plus: "RGB" hex triples (`--palette`). */
  list?: (number | string)[];
  /** A .cpcpal / .cpcpal12 file (`--palette-file`). */
  file?: string;
}

export interface Recipe {
  format: 'cpcimp';
  version: 1;
  source: string;
  output?: string;
  target: ImportTarget;
  mode?: 0 | 1 | 2;
  name?: string;
  kind?: 'sprite' | 'tiles';
  frame?: string;
  /** Tiles: tile width in pixels (`--tile-width`); absent = 8. */
  tileWidth?: number;
  dedupe?: boolean;
  masked?: boolean;
  transparent?: string;
  palette?: PalRef;
  pen0?: number;
  /** false = `--no-palette`. */
  emitPalette?: boolean;
  writePalette?: string;
  zxSprite?: boolean;
  plus?: { packed?: boolean; format?: PlusFormat; palette?: PalRef };
  grid?: GridSpec;
  /** Fields this version does not know, kept so a newer file survives a save. */
  [extra: string]: unknown;
}

export class RecipeError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'RecipeError';
  }
}

export function newRecipe(source = '', over: Partial<Recipe> = {}): Recipe {
  return { format: 'cpcimp', version: 1, source, target: 'cpc', mode: 1, kind: 'sprite', emitPalette: true, ...over };
}

// ------------------------------------------------------------------ JSON

const KEY_ORDER = [
  'format', 'version', 'source', 'output', 'target', 'mode', 'name', 'kind', 'frame', 'tileWidth', 'dedupe', 'masked',
  'transparent', 'palette', 'pen0', 'emitPalette', 'writePalette', 'zxSprite', 'plus', 'grid',
];

export function serialiseRecipe(r: Recipe): string {
  const out: Record<string, unknown> = {};
  for (const k of KEY_ORDER) if (r[k] !== undefined) out[k] = r[k];
  for (const k of Object.keys(r)) if (!(k in out) && r[k] !== undefined) out[k] = r[k];
  return JSON.stringify(out, null, 2) + '\n';
}

const isObj = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);

function checkField(r: Record<string, unknown>, key: string, ok: (v: unknown) => boolean, what: string): void {
  if (r[key] !== undefined && !ok(r[key])) throw new RecipeError(`"${key}" must be ${what}`);
}

/** Checks the shape of a recipe object (not the converter's rules: those come back from the run). */
export function validateRecipe(raw: unknown): Recipe {
  if (!isObj(raw)) throw new RecipeError('a .cpcimp file must hold one JSON object');
  if (raw.format !== 'cpcimp') throw new RecipeError('"format" must be "cpcimp"');
  if (typeof raw.version !== 'number' || !Number.isInteger(raw.version) || raw.version < 1) throw new RecipeError('"version" must be 1');
  if (raw.version > 1) throw new RecipeError(`this recipe is version ${raw.version}; this CPCBuild Studio reads version 1. Update the extension.`);
  const str = (v: unknown): boolean => typeof v === 'string';
  const bool = (v: unknown): boolean => typeof v === 'boolean';
  checkField(raw, 'source', str, 'a path string');
  checkField(raw, 'output', str, 'a path string');
  checkField(raw, 'target', (v) => v === 'cpc' || v === 'plus-sprite' || v === 'plus-palette' || v === 'spectrum', '"cpc", "plus-sprite", "plus-palette" or "spectrum"');
  checkField(raw, 'mode', (v) => v === 0 || v === 1 || v === 2, '0, 1 or 2');
  checkField(raw, 'name', str, 'a string');
  checkField(raw, 'kind', (v) => v === 'sprite' || v === 'tiles', '"sprite" or "tiles"');
  checkField(raw, 'frame', str, 'a "WxH" string');
  checkField(raw, 'tileWidth', (v) => typeof v === 'number' && Number.isInteger(v) && v >= 1, 'a whole number of pixels');
  checkField(raw, 'dedupe', bool, 'true or false');
  checkField(raw, 'masked', bool, 'true or false');
  checkField(raw, 'transparent', str, 'an RRGGBB string');
  checkField(raw, 'pen0', (v) => typeof v === 'number' && Number.isInteger(v), 'a whole number');
  checkField(raw, 'emitPalette', bool, 'true or false');
  checkField(raw, 'writePalette', str, 'a path string');
  checkField(raw, 'zxSprite', bool, 'true or false');
  const palOk = (v: unknown): boolean => isObj(v) && (v.list === undefined || (Array.isArray(v.list) && v.list.every((x) => typeof x === 'number' || typeof x === 'string'))) && (v.file === undefined || typeof v.file === 'string');
  checkField(raw, 'palette', palOk, 'an object {"list": [...]} or {"file": "..."}');
  checkField(raw, 'plus', (v) => isObj(v) && (v.packed === undefined || bool(v.packed)) && (v.format === undefined || v.format === 'bas' || v.format === 'asm' || v.format === 'bin') && (v.palette === undefined || palOk(v.palette)), 'an object {"packed", "format", "palette"}');
  if (raw.grid !== undefined) {
    const g = raw.grid;
    const num = (k: string): boolean => isObj(g) && typeof g[k] === 'number' && Number.isInteger(g[k]) && (g[k] as number) >= 0;
    if (!isObj(g) || !['cellW', 'cellH', 'marginX', 'marginY', 'spacingX', 'spacingY'].every(num) || !Array.isArray(g.exclude) || !g.exclude.every((x) => Number.isInteger(x)) || (g.columns !== undefined && !(Number.isInteger(g.columns) && (g.columns as number) >= 1))) {
      throw new RecipeError('"grid" must be {"cellW","cellH","marginX","marginY","spacingX","spacingY","exclude":[...]} with whole numbers');
    }
  }
  const r = raw as Recipe;
  return { ...r, source: r.source ?? '', target: r.target ?? 'cpc' };
}

/** Parses a .cpcimp file. Empty text is a new, empty recipe. */
export function parseRecipe(text: string): Recipe {
  if (!text.trim()) return newRecipe('');
  let raw: unknown;
  try {
    raw = JSON.parse(text);
  } catch (e) {
    throw new RecipeError(`not valid JSON (${(e as Error).message})`);
  }
  return validateRecipe(raw);
}

// ------------------------------------------------------------------ edits

/**
 * What the importer webview asks for. `set` merges fields (a `null` value removes the field);
 * `cells` includes / excludes grid cells; `replace` swaps the whole recipe (command-line import).
 */
export type RecipeOp =
  | { op: 'set'; patch: { [field: string]: unknown }; label?: string }
  | { op: 'cells'; cells: number[]; include: boolean }
  | { op: 'replace'; recipe: Recipe; label?: string };

export type RecipeOutcome = { state: Recipe; label: string } | { error: string };

export function applyRecipeOp(state: Recipe, op: RecipeOp): RecipeOutcome {
  let next: Recipe;
  let label: string;
  try {
    if (op.op === 'set') {
      const merged: { [k: string]: unknown } = { ...state };
      for (const [k, v] of Object.entries(op.patch)) {
        if (k === 'format' || k === 'version') continue;
        if (v === null || v === undefined) delete merged[k];
        else merged[k] = v;
      }
      next = validateRecipe(merged);
      label = op.label ?? `Change ${Object.keys(op.patch).join(', ')}`;
    } else if (op.op === 'cells') {
      if (!state.grid) return { error: 'grid extraction is off' };
      const ex = new Set(state.grid.exclude);
      for (const c of op.cells) {
        if (op.include) ex.delete(c);
        else ex.add(c);
      }
      next = { ...state, grid: { ...state.grid, exclude: [...ex].sort((a, b) => a - b) } };
      label = op.include ? 'Include grid cells' : 'Exclude grid cells';
    } else {
      next = validateRecipe(op.recipe);
      label = op.label ?? 'Replace recipe';
    }
  } catch (e) {
    return { error: (e as Error).message };
  }
  if (serialiseRecipe(next) === serialiseRecipe(state)) return { error: 'unchanged' };
  return { state: next, label };
}

// ------------------------------------------------------------------ names and paths

export function effectiveName(r: Recipe): string {
  return r.name ?? defaultName(r.source || 'img');
}

/** The output file img2cpc.py writes (-o): the recipe's, else beside the source. */
export function effectiveOutput(r: Recipe): string {
  if (r.output) return r.output;
  const ext = r.target === 'cpc' || r.target === 'spectrum' ? 'bas' : (r.plus?.format ?? 'bas');
  const stem = r.source.replace(/\.[^./]*$/, '');
  return `${stem || 'out'}.${ext}`;
}

/** The files a run writes, relative to the root. */
export function outputsOf(r: Recipe): string[] {
  const out = effectiveOutput(r);
  const files = [out];
  if (r.target === 'plus-sprite' && r.plus?.format === 'bin') files.push(out.replace(/\.[^./]*$/, '') + '.pal');
  if (r.writePalette && r.target === 'cpc') files.push(r.writePalette);
  return files;
}

/** Files whose change makes the output stale. */
export function inputsOf(r: Recipe): string[] {
  const files = [r.source];
  if (r.palette?.file) files.push(r.palette.file);
  if (r.plus?.palette?.file) files.push(r.plus.palette.file);
  return files.filter(Boolean);
}

// ------------------------------------------------------------------ recipe <-> argv

/**
 * The command line (without the program name) for a recipe. Fixed order, which is the order the
 * repo's build scripts use:
 *   target flags (--mode N | --plus-sprite [--packed] [--plus-format F] | --plus-palette | --spectrum [--zx-sprite])
 *   --name N, [--sprite|--tiles [--tile-width PX]] [--dedupe] [--frame WxH] [--masked], [--transparent RRGGBB],
 *   [--palette L | --palette-file F], [--pen0 N], [--no-palette], [--write-palette F], SOURCE, -o OUTPUT
 * With a grid the frame is the cell size (sprites) and the source is the recipe's source (the sheet
 * is composed in memory).
 */
export function recipeToArgv(r: Recipe): string[] {
  const a: string[] = [];
  switch (r.target) {
    case 'cpc':
      a.push('--mode', String(r.mode ?? 1));
      break;
    case 'plus-sprite':
      a.push('--plus-sprite');
      if (r.plus?.packed) a.push('--packed');
      if (r.plus?.format && r.plus.format !== 'bas') a.push('--plus-format', r.plus.format);
      break;
    case 'plus-palette':
      a.push('--plus-palette');
      if (r.plus?.format && r.plus.format !== 'bas') a.push('--plus-format', r.plus.format);
      break;
    case 'spectrum':
      a.push('--spectrum');
      if (r.zxSprite) a.push('--zx-sprite');
      break;
  }
  a.push('--name', effectiveName(r));
  if (r.target === 'cpc') {
    if (r.kind === 'tiles') {
      a.push('--tiles');
      if (r.tileWidth !== undefined && r.tileWidth !== 8) a.push('--tile-width', String(r.tileWidth));
    } else if (r.kind === 'sprite') a.push('--sprite');
    if (r.dedupe) a.push('--dedupe');
    const frame = r.grid && r.kind !== 'tiles' ? `${r.grid.cellW}x${r.grid.cellH}` : r.frame;
    if (frame) a.push('--frame', frame);
    if (r.masked) a.push('--masked');
  }
  if (r.transparent) a.push('--transparent', r.transparent);
  const pal = r.target === 'plus-sprite' || r.target === 'plus-palette' ? r.plus?.palette : r.target === 'cpc' ? r.palette : undefined;
  if (pal?.file) a.push('--palette-file', pal.file);
  else if (pal?.list && pal.list.length) a.push('--palette', pal.list.join(','));
  if (r.target === 'cpc') {
    if (r.pen0 !== undefined) a.push('--pen0', String(r.pen0));
    if (r.emitPalette === false) a.push('--no-palette');
    if (r.writePalette) a.push('--write-palette', r.writePalette);
  }
  a.push(r.source, '-o', effectiveOutput(r));
  return a;
}

/** Pre-processing that has no flag: the command line cannot reproduce the result. */
export function preprocessing(r: Recipe): string | undefined {
  return r.grid ? 'grid extraction' : undefined;
}

/** The exact line the panel shows and "copy" copies, or why there is none. */
export function commandLine(r: Recipe): { command?: string; reason?: string } {
  const pre = preprocessing(r);
  if (pre) return { reason: `No single img2cpc command does this: ${pre} is on. The converter runs on a pre-processed image.` };
  if (!r.source) return { reason: 'Choose a source image first.' };
  return { command: 'python3 tools/img2cpc.py ' + recipeToArgv(r).map(shellQuote).join(' ') };
}

const VALUE_FLAGS = new Set(['--mode', '--name', '-o', '--output', '--frame', '--transparent', '--palette', '--palette-file', '--pen0', '--tile-width', '--write-palette', '--plus-format']);
const BOOL_FLAGS = new Set(['--sprite', '--tiles', '--dedupe', '--masked', '--no-palette', '--plus-sprite', '--plus-palette', '--packed', '--spectrum', '--zx-sprite']);

/** Splits a shell line into words (single and double quotes, backslash); no expansion. */
export function shellSplit(line: string): string[] {
  const words: string[] = [];
  let cur = '';
  let has = false;
  let q: '"' | "'" | null = null;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q === "'") {
      if (c === "'") q = null;
      else cur += c;
    } else if (q === '"') {
      if (c === '"') q = null;
      else if (c === '\\' && i + 1 < line.length && '"\\$`'.includes(line[i + 1])) cur += line[++i];
      else cur += c;
    } else if (c === "'" || c === '"') {
      q = c;
      has = true;
    } else if (c === '\\' && i + 1 < line.length) {
      cur += line[++i];
      has = true;
    } else if (/\s/.test(c)) {
      if (cur || has) words.push(cur);
      cur = '';
      has = false;
    } else {
      cur += c;
      has = true;
    }
  }
  if (q) throw new RecipeError('the command line has an unclosed quote');
  if (cur || has) words.push(cur);
  return words;
}

export interface ArgvImport {
  recipe: Recipe;
  /** Words that are not img2cpc.py options (shell variables left in, unknown flags). */
  unrecognised: string[];
}

/**
 * A recipe from a command line (a `$I ...` line of tools/build_assets.sh, with or without the
 * `python3 tools/img2cpc.py` prefix). Throws RecipeError with the tool's own message when the
 * options are not a valid img2cpc command.
 */
export function argvToRecipe(words: readonly string[]): ArgvImport {
  let i = words.findIndex((w) => /(^|[/\\])img2cpc\.py$/.test(w));
  i = i >= 0 ? i + 1 : words[0] === '$I' || /^\$\{?I\}?$/.test(words[0] ?? '') ? 1 : 0;
  const rest = words.slice(i);
  const unrecognised: string[] = [];
  const clean: string[] = [];
  for (let k = 0; k < rest.length; k++) {
    const w = rest[k];
    const flag = w.startsWith('--') && w.includes('=') ? w.slice(0, w.indexOf('=')) : w;
    if (VALUE_FLAGS.has(flag)) {
      clean.push(w);
      if (flag === w && k + 1 < rest.length) clean.push(rest[++k]);
    } else if (BOOL_FLAGS.has(w)) clean.push(w);
    else if (w.startsWith('-') && w.length > 1) unrecognised.push(w);
    else clean.push(w);
  }
  for (const w of clean) if (/\$[{A-Za-z(]/.test(w)) unrecognised.push(w);
  let a: CliArgs;
  try {
    a = parseArgs(clean);
  } catch (e) {
    throw new RecipeError(e instanceof Img2cpcError ? e.message : (e as Error).message);
  }
  const o = a.options;
  const r = newRecipe(normPath(a.image));
  delete r.kind;
  delete r.emitPalette;
  delete r.mode;
  if (o.plusSprite) r.target = 'plus-sprite';
  else if (o.plusPalette) r.target = 'plus-palette';
  else if (o.spectrum) r.target = 'spectrum';
  else {
    r.target = 'cpc';
    r.mode = o.mode;
  }
  const has = (f: string): boolean => clean.includes(f);
  const name = o.name;
  if (name !== defaultName(a.image)) r.name = name;
  else if (clean.some((w) => w === '--name' || w.startsWith('--name='))) r.name = name;
  if (r.target === 'cpc') {
    if (has('--tiles')) r.kind = 'tiles';
    else if (has('--sprite')) r.kind = 'sprite';
    if (o.tileWidth !== undefined && o.tileWidth !== 8) r.tileWidth = o.tileWidth;
    if (o.dedupe) r.dedupe = true;
    if (o.frame) r.frame = o.frame;
    if (o.masked) r.masked = true;
    if (o.pen0 !== undefined) r.pen0 = o.pen0;
    if (o.noPalette) r.emitPalette = false;
    if (a.writePalette) r.writePalette = a.writePalette;
  }
  if (o.zxSprite) r.zxSprite = true;
  const transparentWord = (() => {
    const k = clean.findIndex((w) => w === '--transparent' || w.startsWith('--transparent='));
    if (k < 0) return undefined;
    return clean[k].includes('=') ? clean[k].slice(clean[k].indexOf('=') + 1) : clean[k + 1];
  })();
  if (transparentWord) r.transparent = transparentWord.replace(/^#+/, '');
  const palRef: PalRef = {};
  if (a.paletteFile) palRef.file = a.paletteFile;
  else if (o.palette !== undefined) {
    palRef.list = r.target === 'cpc' ? parsePalList(o.palette) : o.palette.split(/[,\s]+/).filter(Boolean);
  }
  if (palRef.file || palRef.list) {
    if (r.target === 'cpc') r.palette = palRef;
    else r.plus = { ...(r.plus ?? {}), palette: palRef };
  }
  if (o.packed) r.plus = { ...(r.plus ?? {}), packed: true };
  if (o.plusFormat && o.plusFormat !== 'bas') r.plus = { ...(r.plus ?? {}), format: o.plusFormat };
  if (a.output) r.output = a.output;
  return { recipe: r, unrecognised };
}

// ------------------------------------------------------------------ grid extraction

/** Builds the contiguous sheet from the selected cells. Throws Img2cpcError when no cell fits. */
export function composeSheet(img: RgbaImage, g: GridSpec): RgbaImage {
  const lay = gridLayout(g, img.width, img.height);
  if (!lay.cols || !lay.rows) {
    throw new Img2cpcError(`the grid has no cell: the image is ${img.width}x${img.height}, a cell is ${g.cellW}x${g.cellH} after a margin of ${g.marginX},${g.marginY}`);
  }
  if (!lay.selected.length) throw new Img2cpcError('no grid cell is selected');
  const w = lay.sheetCols * g.cellW, h = lay.sheetRows * g.cellH;
  const data = new Uint8Array(w * h * 4);
  lay.selected.forEach((cell, n) => {
    const sx = g.marginX + (cell % lay.cols) * (g.cellW + g.spacingX);
    const sy = g.marginY + Math.floor(cell / lay.cols) * (g.cellH + g.spacingY);
    const dx = (n % lay.sheetCols) * g.cellW, dy = Math.floor(n / lay.sheetCols) * g.cellH;
    for (let y = 0; y < g.cellH; y++) {
      const from = ((sy + y) * img.width + sx) * 4;
      data.set(img.data.subarray(from, from + g.cellW * 4), ((dy + y) * w + dx) * 4);
    }
  });
  return { width: w, height: h, data };
}

