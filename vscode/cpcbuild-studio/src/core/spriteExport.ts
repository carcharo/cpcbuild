/**
 * spriteExport.ts -- from a sprite / tile document to the .bas (or .asm / .bin) img2cpc.py would write for
 * the same pixels and options (spec 4.2 "Output"). The editor holds pen indices, so it feeds the converter's
 * packing stage directly (`penBody` for CPC modes; the Plus packer here) instead of going through RGB: the
 * only difference from a PNG round trip is that two pens of one colour stay distinct. src/core/spriteExport.test.ts
 * runs tools/img2cpc.py on a PNG rendering of the document and compares the files byte for byte.
 */
import { newImage, setPixel, type RgbaImage } from './image';
import { buildPalette, fmtArray, fmtAsm, fmtConst, makeHeader, penBody, shellQuote, type Options } from './img2cpc';
import { asicEntry, fwRgb, nearest, parseRgb12List, rgb12To8, type RGB } from './palette';
import type { PenGrid } from './pixels';
import { analyse, MAX_PLUS_COLOURS, resolvePalette, type Grid, type ResolvedPalette, type SpriteState } from './spriteDoc';

export type HeaderStyle = 'img2cpc' | 'studio' | 'none';

export interface ExportContext {
  /** Palette as resolved (file contents read by the caller); defaults to the inline palette. */
  palette?: ResolvedPalette;
  /** The "Source:" of the header and the image argument of the equivalent command (the document's file name). */
  source: string;
  header?: HeaderStyle;
}

export interface ExportResult {
  /** The .bas / .asm text (empty for plus format bin). */
  text: string;
  /** plus format bin: the sprite data and the 30-byte palette (.pal beside it). */
  bin?: Uint8Array;
  palBin?: Uint8Array;
  /** The equivalent img2cpc.py command line (arguments after the program name). */
  argv: string[];
  /** Sheet size the equivalent image would have. */
  sheet: { w: number; h: number };
}

export class ExportError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'ExportError';
  }
}

/** Mapping of the document to img2cpc.py's arguments (spec 4.2 "Output" table). `image` is the image path argument. */
export function equivalentArgs(s: SpriteState, image: string, palette: ResolvedPalette = resolvePalette(s)): string[] {
  const a: string[] = [];
  if (s.kind === 'plus') {
    a.push('--plus-sprite', '--name', s.name);
    if (s.packed) a.push('--packed');
    if (s.plusFormat !== 'bas') a.push('--plus-format', s.plusFormat);
    if (palette.colours) a.push('--palette', palette.colours.join(','));
    return a.concat(image);
  }
  a.push('--mode', String(s.mode), '--name', s.name, s.type === 'til' ? '--tiles' : '--sprite');
  if (s.type === 'til') {
    if (s.dedupe) a.push('--dedupe');
  } else {
    if (s.items.length > 1) a.push('--frame', `${s.w}x${s.h}`);
    if (s.masked) a.push('--masked');
  }
  if ('file' in s.palette) a.push('--palette-file', s.palette.file);
  else if (palette.pens) a.push('--palette', palette.pens.join(','));
  if (!s.emitPalette) a.push('--no-palette');
  return a.concat(image);
}

/** The equivalent command as one shell line, for "copy command". */
export function equivalentCommand(s: SpriteState, image: string, palette?: ResolvedPalette): string {
  return 'python3 tools/img2cpc.py ' + equivalentArgs(s, image, palette).map(shellQuote).join(' ');
}

function head(style: HeaderStyle, cmt: string, argv: string[], ctx: ExportContext, w: number, h: number, modeTxt: string, desc: string): string {
  if (style === 'none') return '';
  if (style === 'studio') {
    return `${cmt} Generated by CPCBuild Studio from ${ctx.source}\n${cmt} ${desc}\n${cmt} Do not edit; change ${ctx.source} and generate again.\n\n`;
  }
  return makeHeader(cmt, { argv, source: ctx.source }, w, h, modeTxt, desc);
}

/** The pen grid of the sheet the document stands for: items side by side in one row. */
function sheetGrid(items: Grid[], w: number, h: number): PenGrid {
  const rows: PenGrid = [];
  for (let y = 0; y < h; y++) {
    const row: (number | null)[] = [];
    for (const g of items) for (let x = 0; x < w; x++) row.push(g[y][x] < 0 ? null : g[y][x]);
    rows.push(row);
  }
  return rows;
}

/** Writes the document the way img2cpc.py would. Throws ExportError with the tool's wording. */
export function exportAsset(s: SpriteState, ctx: ExportContext): ExportResult {
  const palette = ctx.palette ?? resolvePalette(s);
  const a = analyse(s, palette);
  if (a.problems.length) throw new ExportError(a.problems[0]);
  const style = ctx.header ?? 'img2cpc';
  const argv = equivalentArgs(s, ctx.source, palette);
  const n = s.items.length;
  const sheet = { w: n * s.w, h: s.h };
  try {
    if (s.kind === 'plus') return exportPlus(s, palette, argv, style, ctx, sheet);
    const pens = buildPalette([], s.mode, palette.pens, undefined); // the tool's checks on a fixed palette
    const o: Options = { name: s.name, mode: s.mode, tiles: s.type === 'til', dedupe: s.dedupe, masked: s.masked, noPalette: !s.emitPalette };
    if (s.type === 'spr' && n > 1) o.frame = `${s.w}x${s.h}`;
    const body = penBody(sheetGrid(s.items, s.w, s.h), sheet.w, sheet.h, pens, o);
    return { text: head(style, "'", argv, ctx, sheet.w, sheet.h, `mode ${s.mode}`, body.desc) + body.body, argv, sheet };
  } catch (e) {
    throw e instanceof Error && e.name === 'Img2cpcError' ? new ExportError(e.message) : e;
  }
}

function exportPlus(s: SpriteState, palette: ResolvedPalette, argv: string[], style: HeaderStyle, ctx: ExportContext, sheet: { w: number; h: number }): ExportResult {
  const colours = parseRgb12List((palette.colours ?? []).join(','));
  const data: number[] = [];
  for (const g of s.items) {
    const px: number[] = [];
    for (const r of g) for (const v of r) px.push(v < 0 ? 0 : v);
    if (s.packed) for (let i = 0; i < px.length; i += 2) data.push((px[i] << 4) | px[i + 1]);
    else data.push(...px);
  }
  const pal: number[] = [];
  for (const c of colours) pal.push(...asicEntry(c));
  for (let i = colours.length; i < MAX_PLUS_COLOURS; i++) pal.push(0, 0);
  const frames = s.items.length;
  const size = data.length / frames;
  if (s.plusFormat === 'bin') return { text: '', bin: Uint8Array.from(data), palBin: Uint8Array.from(pal), argv, sheet };
  const desc = `${frames} sprite(s) of ${size} bytes (${s.packed ? 'packed 4-bit' : 'one byte per pixel'}), palette 15 entries`;
  const consts: [string, number][] = [[s.name + '_FRAMES', frames], [s.name + '_SIZE', size], [s.name + '_PALN', MAX_PLUS_COLOURS]];
  const arrays: [string, number[]][] = [[s.name, data], [s.name + '_pal', pal]];
  const asm = s.plusFormat === 'asm';
  const body = asm
    ? [...arrays.map(([nm, d]) => fmtAsm(nm, d)), ...consts.map(([nm, v]) => `${nm} EQU ${v}\n`)].join('\n')
    : [...arrays.map(([nm, d]) => fmtArray(nm, d)), ...consts.map(([nm, v]) => fmtConst(nm, v))].join('\n');
  return { text: head(style, asm ? ';' : "'", argv, ctx, sheet.w, sheet.h, 'CPC Plus', desc) + body, argv, sheet };
}

// ------------------------------------------------------- rendering

/** RGB of every pen/colour the document can show (index = pen; plus: index = sprite colour, 0 unused). */
export function paletteRgb(s: SpriteState, palette: ResolvedPalette = resolvePalette(s)): (RGB | undefined)[] {
  if (s.kind === 'plus') return [undefined, ...(palette.colours ?? []).map((c) => rgb12To8([parseInt(c[0], 16), parseInt(c[1], 16), parseInt(c[2], 16)]))];
  return (palette.pens ?? []).map((p) => fwRgb(p));
}

/** The sheet as RGBA (items side by side, transparent = alpha 0): what `img2cpc.py --palette` would be given. */
export function renderSheet(s: SpriteState, palette: ResolvedPalette = resolvePalette(s)): RgbaImage {
  const rgb = paletteRgb(s, palette);
  const img = newImage(Math.max(1, s.items.length) * s.w, s.h);
  s.items.forEach((g, i) => {
    for (let y = 0; y < s.h; y++)
      for (let x = 0; x < s.w; x++) {
        const v = g[y][x];
        const c = v >= 0 ? rgb[v] : undefined;
        if (c) setPixel(img, i * s.w + x, y, c[0], c[1], c[2], 255);
      }
  });
  return img;
}

/** Quantises an image into a pen grid by the document's palette (nearest colour; alpha < 128 = transparent). */
export function gridFromImage(s: SpriteState, img: RgbaImage, palette: ResolvedPalette = resolvePalette(s)): number[][] {
  const rgb = paletteRgb(s, palette);
  const list: RGB[] = [];
  const idx: number[] = [];
  rgb.forEach((c, i) => { if (c) { list.push(c); idx.push(i); } });
  if (!list.length) throw new ExportError('the palette has no colours to match the image to');
  const rows: number[][] = [];
  for (let y = 0; y < img.height; y++) {
    const row: number[] = [];
    for (let x = 0; x < img.width; x++) {
      const i = (y * img.width + x) * 4;
      row.push(img.data[i + 3] < 128 ? -1 : idx[nearest([img.data[i], img.data[i + 1], img.data[i + 2]], list)]);
    }
    rows.push(row);
  }
  return rows;
}

// ------------------------------------------------------- snippets

export interface AssetSnippet {
  id: string;
  label: string;
  text: string;
}

/** Copy-as texts: the include, the draw call and the data (spec 4.2 US12). `rel` is the include path. */
export function assetSnippets(s: SpriteState, rel: string, data?: string): AssetSnippet[] {
  const n = s.name;
  const out: AssetSnippet[] = [{ id: 'include', label: '#include line', text: `#include "${rel}"\n` }];
  if (s.kind === 'plus') {
    out.push({
      id: 'use',
      label: 'SpriteSetImage call',
      text: `SpriteSetImage${s.packed ? 'Packed' : ''}(0, @${n}(0))\n`,
    });
  } else if (s.type === 'til') {
    out.push({ id: 'use', label: 'SetTileSet + DoTile8', text: `SetTileSet(@${n}(0))\nDoTile8(x, y, 0)\n` });
  } else {
    const pal = s.emitPalette ? `SetPalette(@${n}_pal(0), ${n}_PENS)\n` : '';
    out.push({
      id: 'use',
      label: s.masked ? 'PutSpriteMasked call' : 'PutSprite call',
      text: `${pal}${s.masked ? 'PutSpriteMasked' : 'PutSprite'}(x, y, ${n}_W, ${n}_H, @${n}(frame * ${n}_SIZE))\n`,
    });
  }
  if (data !== undefined) out.push({ id: 'data', label: 'Data (the generated file)', text: data });
  return out;
}
