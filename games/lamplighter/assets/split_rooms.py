#!/usr/bin/env python3
"""split_rooms.py -- cuts Lamplighter's tower.tmx into per-room data for rooms.bas.

    split_rooms.py tower.tmx -o rooms.bas

tools/tmx2bas.py reads the tile layer (the whole 60 x 92 map); this lays it
out room by room: 12 rooms of 20 x 23 bytes, row-major from the room's cell
(0, 0), which is what TileRestore needs, room r at offset 460 * r in
`rooms`. Room r is at grid column r % 3, row r // 3 (row 0 at the top).

The object layer becomes `robj`, 5-byte records [type, a, b, c, d] per room,
ended by a zero type, and `roff(r)`, the offset of room r's list:
  type 1  start      a, b = cell column, row of the sprite's top left
  type 2  enemy      a = kind (1 walker, 2 floater, 3 bat), b, c = cell
                     column, row, d = range in cells
and `RoomName(id)`, from the map property "names" (comma separated).
"""
import argparse
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "tools"))
import tmx2bas  # noqa: E402

RW, RH, GW, GH = 20, 23, 3, 4


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tmx", type=Path)
    ap.add_argument("-o", "--output", type=Path, required=True)
    args = ap.parse_args()
    tiles, w, h, _ = tmx2bas.convert(args.tmx, "tiles", None, 0)
    if (w, h) != (RW * GW, RH * GH):
        sys.exit(f"split_rooms: {w}x{h} cells, expected {RW * GW}x{RH * GH}")
    root = ET.parse(args.tmx).getroot()
    rooms = []
    for r in range(GW * GH):
        gx, gy = r % GW, r // GW
        for y in range(RH):
            base = (gy * RH + y) * w + gx * RW
            rooms += tiles[base:base + RW]
    objs = {r: [] for r in range(GW * GH)}
    for o in root.iter("object"):
        x, y = int(float(o.get("x"))) // 8, int(float(o.get("y"))) // 8
        r = (y // RH) * GW + x // RW
        c, row = x % RW, y % RH
        props = {p.get("name"): p.get("value") for p in o.iter("property")}
        t = o.get("type")
        if t == "start":
            objs[r].append((1, c, row, 0, 0))
        elif t == "enemy":
            objs[r].append((2, int(props["kind"]), c, row, int(props.get("range", 0))))
        else:
            sys.exit(f"split_rooms: unknown object type {t!r}")
    # tile numbers of tiles.png: 5 lamp, 7 door (game.bas keeps up to 8 of each per room)
    for r in range(GW * GH):
        room = rooms[r * RW * RH:(r + 1) * RW * RH]
        assert room.count(5) <= 8 and room.count(7) <= 8, f"room {r}: more than 8 lamps or doors"
    lamps_total = rooms.count(5)
    names = next(p.get("value") for p in root.find("properties") if p.get("name") == "names").split(",")
    assert len(names) == GW * GH
    robj, roff = [], []
    for r in range(GW * GH):
        roff.append(len(robj))
        assert sum(1 for o in objs[r] if o[0] == 2) <= 4, f"room {r}: more than 4 enemies"
        assert sum(1 for o in objs[r] if o[0] == 1) == 1, f"room {r}: needs one start"
        for o in sorted(objs[r]):
            robj += o
        robj += [0, 0, 0, 0, 0]

    def arr(name, vals, typ="UBYTE"):
        lines = []
        for i in range(0, len(vals), 16):
            lines.append("    " + ", ".join(f"${v:02X}" if typ == "UBYTE" else str(v) for v in vals[i:i + 16])
                         + (", _" if i + 16 < len(vals) else " _"))
        return f"DIM {name}({len(vals) - 1}) AS {typ} => {{ _\n" + "\n".join(lines) + "\n}\n\n"

    out = ["' Generated by split_rooms.py (tower.tmx); do not edit, regenerate with build_assets.sh.\n",
           f"' {GW * GH} rooms of {RW} x {RH} cells; room r at offset {RW * RH} * r.\n\n",
           f"CONST ROOMS_N AS UBYTE = {GW * GH}\nCONST ROOM_W AS UBYTE = {RW}\nCONST ROOM_H AS UBYTE = {RH}\n"
           f"CONST ROOM_SIZE AS UINTEGER = {RW * RH}\nCONST LAMPS_TOTAL AS UBYTE = {lamps_total}\n\n",
           arr("rooms", rooms), arr("robj", robj), arr("roff", roff, "UINTEGER"),
           "FUNCTION RoomName(id AS UBYTE) AS STRING\n"]
    for r, n in enumerate(names):
        out.append(f'  IF id = {r} THEN RETURN "{n}"\n')
    out.append('  RETURN ""\nEND FUNCTION\n')
    args.output.write_text("".join(out))


if __name__ == "__main__":
    main()
